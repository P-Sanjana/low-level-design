class TV:
    def turnOn(self):
        print("TV is ON.")

    def turnOff(self):
        print("TV if OFF.")

    def setHDMIPort(self, port):
        print(f"TV HDMI is set to port {port}.")

class SoundSystem:
    def turnOn(self):
        print("Sound system is ON.")

    def turnOff(self):
        print("Sound system is OFF.")

    def setVolume(self, volume):
        print(f"Sound system volume is set to {volume}.")

class DVDPlayer:
    def turnOn(self):
        print("DVD player is ON.")

    def turnOff(self):
        print("DVD player is OFF.")

    def play(self):
        print("DVD player is playing.")

